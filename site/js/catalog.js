/* Fetches and interprets catalog.json.
 *
 * Everything the UI knows about datasets, dimensions, geographies, and years
 * comes from here. No dataset name, category value, or year range is hardcoded
 * in a component — if it were, publishing new data would require a site
 * rebuild, which is exactly what this architecture avoids.
 */

import { CATALOG_URL } from './config.js';

let cached = null;

/* Keys the UI cannot render without. Checked on load so a stale or malformed
 * catalog produces a clear, actionable message instead of a blank page — the
 * failure mode when the published catalog briefly lost these. */
const REQUIRED = ['entries', 'datasets', 'dimensions', 'geographies', 'measures', 'source'];

export async function loadCatalog() {
  if (cached) return cached;
  const res = await fetch(CATALOG_URL);
  if (!res.ok) throw new Error(`Catalog unavailable (HTTP ${res.status}) at ${CATALOG_URL}`);

  let json;
  try {
    json = await res.json();
  } catch {
    throw new Error(`Catalog at ${CATALOG_URL} is not valid JSON.`);
  }

  const missing = REQUIRED.filter((k) => !json[k]);
  if (missing.length) {
    throw new Error(
      `The published catalog is missing: ${missing.join(', ')}. ` +
      `It was generated by pipeline ${json.pipeline_version || 'unknown'} at ` +
      `${json.generated_at || 'unknown time'}. Re-run the data refresh workflow ` +
      `to regenerate it.`
    );
  }
  if (!json.entries.length) throw new Error('The published catalog lists no data files.');

  cached = json;
  return cached;
}

/** Geography levels that actually have data, in a sensible coarse-to-fine order. */
export function geographies(cat) {
  const order = ['nation', 'state', 'county', 'cbsa', 'czone', 'puma', 'zcta', 'tract', 'cd'];
  const present = new Set(cat.entries.map((e) => e.geography));
  const meta = cat.geographies || {};
  // Any level present in entries but unknown to `order` still gets offered,
  // so publishing a new geography needs no site change.
  const extras = [...present].filter((g) => !order.includes(g)).sort();
  return [...order.filter((g) => present.has(g)), ...extras].map((g) => ({
    id: g,
    label: meta[g]?.label || g,
    ...(meta[g] || {}),
  }));
}

export function datasets(cat) {
  return Object.entries(cat.datasets).map(([id, d]) => ({ id, ...d }));
}

/** Dimension definition, with its declared values and labels. */
export function dimension(cat, name) {
  const d = cat.dimensions[name];
  if (!d) return null;
  return {
    id: name,
    label: d.label || name,
    note: d.note,
    footnote: d.footnote,
    values: (d.values || []).map((v) => ({
      code: v.code,
      label: v.label ?? String(v.code),
      residual: !!v.residual,
    })),
  };
}

/* Display names for every geography level, loaded once.
 *
 * Loaded for ALL levels rather than the currently selected one: search must
 * find a county while the user happens to have "state" selected, and a picker
 * listing raw FIPS codes is unusable. The files are small and year-independent.
 */
let namesCache = null;

export async function loadNames(cat) {
  if (namesCache) return namesCache;
  const levels = Object.entries(cat.names || {});
  const loaded = await Promise.all(
    levels.map(async ([level, url]) => {
      try {
        const res = await fetch(url);
        return [level, res.ok ? await res.json() : {}];
      } catch {
        return [level, {}];
      }
    })
  );
  namesCache = Object.fromEntries(loaded);
  return namesCache;
}

/** Flat, searchable list across every level, coarse levels first so a search
 *  for "Washington" surfaces the state before the counties. */
export function placeIndex(cat, names) {
  const order = geographies(cat).map((g) => g.id);
  const out = [];
  for (const level of order) {
    const label = cat.geographies[level]?.label || level;
    // Sorted explicitly: JavaScript reorders object keys that parse as
    // integers, so "10001" (Delaware) would come before "01001" (Alabama,
    // which keeps a leading zero and stays a string key). Alphabetical by
    // name is what a picker wants regardless.
    const entries = Object.entries(names[level] || {}).sort((a, b) =>
      a[1].localeCompare(b[1])
    );
    for (const [geo_id, name] of entries) {
      out.push({ geo_id, name, level, levelLabel: label });
    }
  }
  return out;
}

export function yearsFor(cat, dataset, geography) {
  return cat.entries
    .filter((e) => e.dataset === dataset && e.geography === geography)
    .map((e) => e.year)
    .sort((a, b) => a - b);
}

export function isPreliminary(cat, dataset, year) {
  return (cat.datasets[dataset]?.preliminary_years || []).includes(year);
}

export function entryUrl(cat, dataset, geography, year) {
  return cat.entries.find(
    (e) => e.dataset === dataset && e.geography === geography && e.year === year
  )?.url;
}

/** All-years file for a (dataset, geography), when one is published.
 *  Multi-year queries should use this: reading 25 per-year files means 25
 *  round trips, which dominates latency on a cold CDN edge. */
export function combinedUrl(cat, dataset, geography) {
  return (cat.combined || []).find(
    (c) => c.dataset === dataset && c.geography === geography
  )?.url;
}

/** Which measure to default to, per the published guidance.
 *  Post-processed below the population threshold, raw above it. */
export function defaultMeasure(cat, population) {
  const threshold = cat.measure_selection_population_threshold;
  if (population == null || threshold == null) {
    return Object.entries(cat.measures).find(([, m]) => m.default)?.[0] || 'n_noise_postprocessed';
  }
  return population > threshold ? 'n_noise' : 'n_noise_postprocessed';
}
